#!/usr/bin/env node
/**
 * UI inventory for the component-kit migration.
 *
 * Counts hand-rolled controls per file so the migration order is driven by
 * evidence rather than by whichever file someone happened to open. Writes
 * `docs/ui-audit.md`; run with `--check` to fail when a file regresses past its
 * budget (used by CI once the migration is complete).
 *
 * Raw means "not the shared kit": a <button>/<select>/<input> written directly
 * in a component instead of Button/IconButton/Select/Input.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, relative } from "node:path";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SRC = join(ROOT, "apps/desktop/src");

/** Files that legitimately own raw elements. */
const EXEMPT = [/^ui\//, /\.test\.tsx?$/, /^test\//];

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else if (name.endsWith(".tsx")) files.push(full);
  }
};
walk(SRC);

const count = (text, pattern) => (text.match(pattern) ?? []).length;

const rows = [];
for (const full of files) {
  const rel = relative(SRC, full).replaceAll("\\", "/");
  if (EXEMPT.some((re) => re.test(rel))) continue;
  const text = readFileSync(full, "utf8");
  const buttons = count(text, /<button[\s>]/g);
  const selects = count(text, /<select[\s>]/g);
  const inputs = count(text, /<input[\s>]/g);
  const arbitrary = count(text, /\b(?:h|w|text|gap|p|px|py|m|mx|my|rounded)-\[\d/g);
  const literalColour = count(text, /\b(?:text|bg|border)-(?:red|green|blue|yellow|slate|gray|zinc)-/g);
  const usesKit = /from "\.\/ui"|from "\.\.\/ui"|from "\.\/ui\/|from "\.\.\/ui\//.test(text);
  if (buttons + selects + inputs === 0 && literalColour === 0) continue;
  rows.push({ file: rel, buttons, selects, inputs, arbitrary, literalColour, usesKit });
}

rows.sort((a, b) => b.buttons + b.selects + b.inputs - (a.buttons + a.selects + a.inputs));

const totals = rows.reduce(
  (sum, r) => ({
    buttons: sum.buttons + r.buttons,
    selects: sum.selects + r.selects,
    inputs: sum.inputs + r.inputs,
    arbitrary: sum.arbitrary + r.arbitrary,
    literalColour: sum.literalColour + r.literalColour,
  }),
  { buttons: 0, selects: 0, inputs: 0, arbitrary: 0, literalColour: 0 },
);

const table = [
  "| file | buttons | selects | inputs | arbitrary sizes | literal colours | kit imported |",
  "| --- | ---: | ---: | ---: | ---: | ---: | :---: |",
  ...rows.map(
    (r) =>
      `| \`${r.file}\` | ${r.buttons} | ${r.selects} | ${r.inputs} | ${r.arbitrary} | ${r.literalColour} | ${r.usesKit ? "yes" : "no"} |`,
  ),
].join("\n");

const doc = `# UI audit

Generated by \`node scripts/ui-audit.mjs\` on ${new Date().toISOString().slice(0, 10)}.

## Totals across \`apps/desktop/src\`

| control | count |
| --- | ---: |
| raw \`<button>\` | ${totals.buttons} |
| native \`<select>\` | ${totals.selects} |
| raw \`<input>\` | ${totals.inputs} |
| arbitrary \`h-[..]\`-style sizes | ${totals.arbitrary} |
| literal Tailwind colours (non-token) | ${totals.literalColour} |

"Raw" means the element is written directly instead of coming from
\`apps/desktop/src/ui\`. The kit itself and test files are exempt.

## Migration order

1. \`ui\` — finish the primitive kit (Select, Combobox, Tabs, Dialog, Popover,
   Tooltip, Field family, SegmentedControl, Badge, Toast). Everything else
   depends on it.
2. Toolbar and chart chrome — the most-clicked controls, and the ones whose
   heights drifted most.
3. Dialogs and forms — \`ChartSettingsDialog\`, \`IndicatorSettingsDialog\`,
   \`ApiKeysDialog\`, \`IntervalDialog\`, \`LinkGroupDialog\`, \`TradeConfirmDialog\`.
4. Dock tabs, tables and panels — rows, empty states, headers.
5. Remaining pages — settings, journal, research, trade.

A file is done when it has no raw control that the kit can express, and no
literal colour or arbitrary size that a token covers.

## Per file

${table}

## Budget

The end state is zero raw \`<select>\`, zero literal colours, and raw
\`<button>\` only where a bespoke element is genuinely required (canvas hit
targets, drag handles). \`node scripts/ui-audit.mjs --check\` fails when a file
adds \`<select>\` or a literal colour.
`;

mkdirSync(join(ROOT, "docs"), { recursive: true });
if (process.argv.includes("--check")) {
  const offenders = rows.filter((r) => r.selects > 0 || r.literalColour > 0);
  if (offenders.length > 0) {
    console.error("UI budget exceeded (native <select> or literal colour):");
    for (const r of offenders) console.error(`  ${r.file}: ${r.selects} selects, ${r.literalColour} literal colours`);
    process.exit(1);
  }
  process.stdout.write("UI budget is clean.\n");
} else {
  writeFileSync(join(ROOT, "docs/ui-audit.md"), doc);
  process.stdout.write(
    `Wrote docs/ui-audit.md — ${rows.length} files, ${totals.buttons} buttons, ${totals.selects} selects, ${totals.inputs} inputs.\n`,
  );
}
