import type { AssignExpr, Identifier, Node, Script } from "./ast.js";
import { parse } from "./parser.js";
import { PineSyntaxError } from "./lexer.js";

/** Thrown when the transpiler meets a Pine feature EzyView does not model. */
export class PineUnsupportedError extends Error {
  constructor(
    message: string,
    readonly line: number,
    readonly col: number,
  ) {
    super(`Pine unsupported at ${line}:${col} — ${message}`);
    this.name = "PineUnsupportedError";
  }
}

/** Options gathered from the leading `indicator()`/`strategy()` call. */
export interface ScriptOptions {
  title: string;
  overlay: boolean;
  isStrategy: boolean;
  /** Short names accepted by the chart for `plot()`'s color argument. */
  shortName: string;
}

export const DEFAULT_SCRIPT_OPTIONS: ScriptOptions = {
  title: "Custom script",
  overlay: true,
  isStrategy: false,
  shortName: "Script",
};

/**
 * Compile Pine source to a JS function body.
 *
 * The emitted body is a plain `for` loop over bars: Pine is series-oriented, so
 * each script becomes a per-bar pass over pre-sliced arrays. That keeps `na`
 * propagation and `[n]` offsets honest without a per-value interpreter.
 */
export function transpile(source: string): { code: string; options: ScriptOptions } {
  const script = parse(source);
  return { code: emitScript(script), options: extractOptions(script) };
}

function extractOptions(script: Script): ScriptOptions {
  const call = script.declaration;
  if (!call) return DEFAULT_SCRIPT_OPTIONS;

  const callee = call.callee;
  const name = callee.kind === "Identifier" ? callee.name : "";
  let title = DEFAULT_SCRIPT_OPTIONS.title;
  let overlay = true;
  let shortName: string | undefined;

  const first = call.args[0];
  if (first?.kind === "StringLit") title = first.value;

  // Scan every named argument — returning early on one (e.g. `shorttitle`)
  // would silently drop any option that follows it.
  for (const arg of call.args.slice(1)) {
    if (arg.kind === "AssignExpr" && arg.target.kind === "Identifier") {
      if (arg.target.name === "overlay" && arg.value.kind === "BoolLit") overlay = arg.value.value;
      if (arg.target.name === "shorttitle" && arg.value.kind === "StringLit") shortName = arg.value.value;
    }
  }

  return {
    title,
    overlay,
    isStrategy: name === "strategy",
    shortName: shortName ?? title.slice(0, 12),
  };
}

function emitScript(script: Script): string {
  const out = new Emitter();
  out.line("// generated by @ezyview/pine");
  out.line("const plots = [];");
  out.line("const orders = [];");
  out.declareGlobals();

  // One pass per bar, matching Pine's series semantics.
  out.line("for (let barIndex = 0; barIndex < close.length; barIndex++) {");
  out.indent(() => {
    out.line("const barIndex_ = barIndex;");
    out.line("bar_index = barIndex;");
    out.emitBody(script.body);
    out.line("barIndexUsed = Math.max(barIndexUsed, barIndex_);");
  });
  out.line("}");

  out.line("return { plots, orders, barIndexUsed };");
  return out.toString();
}

/** Emits JS while tracking which names the script has declared. */
class Emitter {
  private lines: string[] = [];
  private depth = 0;
  /** Names bound with `var` survive across bars, so they hoist out of the loop. */
  private varNames = new Set<string>();
  private emittedVars = new Set<string>();
  /**
   * Stable id per plotting call site.
   *
   * The body is emitted once but runs once per bar, so the runtime needs a key
   * that identifies "this `plot()` call" across every iteration. A compile-time
   * counter gives each call site a fixed id — deriving it from `plots.length`
   * at runtime would shift as plots accumulate and defeat the dedupe.
   */
  private plotSiteCount = 0;

  /** Reserve the next plotting call site's id. */
  private nextPlotSite(): number {
    return this.plotSiteCount++;
  }

  /**
   * Stable id per `input()` call site, same idea as {@link plotSiteCount}.
   *
   * The runtime keys a positional input by this compile-time index rather
   * than by `inputs.length` at call time — the body runs once per bar, so a
   * runtime count would mint a fresh key on every iteration and defeat both
   * the per-site dedupe and the optimizer's seeded overrides.
   */
  private inputSiteCount = 0;

  /** Reserve the next input call site's id. */
  private nextInputSite(): number {
    return this.inputSiteCount++;
  }

  line(text: string): void {
    this.lines.push("  ".repeat(this.depth) + text);
  }

  indent(fn: () => void): void {
    this.depth++;
    fn();
    this.depth--;
  }

  declareGlobals(): void {
    // `close` etc. shadow nothing useful, so they are destructured from the
    // context object the runtime passes in. The mid-price series are derived
    // from OHLC by the runtime before the body runs.
    this.line("const { open, high, low, close, volume, hl2, hlc3, ohlc4, inputs } = ctx;");
    this.line("let barIndexUsed = 0;");
    this.line("let bar_index = 0;");
  }

  emitBody(body: Node[]): void {
    for (const stmt of body) this.emitStmt(stmt);
  }

  private emitStmt(node: Node): void {
    switch (node.kind) {
      case "ExprStmt": {
        // A bare call is the common case (`plot(close)`); emit it as a
        // statement so its side effects land in `plots`/`orders`.
        this.line(`${this.expr(node.expression)};`);
        return;
      }
      case "VarDecl": {
        const name = this.safeName(node.name, node.line, node.col);
        if (node.isVar) {
          this.varNames.add(name);
          if (!this.emittedVars.has(name)) {
            this.emittedVars.add(name);
            this.outerLine(`let ${name} = ${node.value ? this.expr(node.value) : "NA"};`);
          }
          return;
        }
        // Non-var locals reset each bar, which is Pine's default.
        this.line(`let ${name} = ${node.value ? this.expr(node.value) : "NA"};`);
        return;
      }
      case "DeclStmt": {
        const name = this.safeName(node.name, node.line, node.col);
        if (node.isVar) {
          this.varNames.add(name);
          if (!this.emittedVars.has(name)) {
            this.emittedVars.add(name);
            this.outerLine(`let ${name} = ${this.expr(node.value)};`);
          }
          return;
        }
        this.line(`let ${name} = ${this.expr(node.value)};`);
        return;
      }
      case "AssignExpr": {
        // Pine's `:=` reassigns; JS uses `=` for both declare and reassign, so
        // the operator normalizes here rather than reaching the output verbatim.
        this.line(`${this.expr(node.target)} = ${this.expr(node.value)};`);
        return;
      }
      case "Block": {
        this.line("{");
        this.indent(() => this.emitBody(node.body));
        this.line("}");
        return;
      }
      case "IfStmt": {
        this.line(`if (truthy(${this.expr(node.test)}, barIndex)) {`);
        this.indent(() => this.emitBody(node.consequent.body));
        if (node.alternate) {
          this.line("} else {");
          this.indent(() => this.emitBody(node.alternate!.body));
        }
        this.line("}");
        return;
      }
      case "ForStmt": {
        if (node.step && node.step.kind === "NumberLit" && node.step.value === 0) {
          throw new PineUnsupportedError("for-loop step must not be 0", node.line, node.col);
        }
        const v = this.safeName(node.variable, node.line, node.col);
        this.line("{");
        this.indent(() => {
          this.line("let __iters = 0;");
          this.line(`for (let ${v} = num(${this.expr(node.from)}); ${v} <= num(${this.expr(node.to)}); ${v} += ${node.step ? `num(${this.expr(node.step)})` : "1"}) {`);
          this.indent(() => {
            this.line("if (++__iters > 100000) throw new Error(\"pine: too many iterations\");");
            this.emitBody(node.body.body);
          });
          this.line("}");
        });
        this.line("}");
        return;
      }
      case "WhileStmt": {
        this.line("{");
        this.indent(() => {
          this.line("let __iters = 0;");
          this.line(`while (truthy(${this.expr(node.test)}, barIndex)) {`);
          this.indent(() => {
            this.line("if (++__iters > 100000) throw new Error(\"pine: too many iterations\");");
            this.emitBody(node.body.body);
          });
          this.line("}");
        });
        this.line("}");
        return;
      }
      case "ReturnStmt": {
        this.line(node.argument ? `return ${this.expr(node.argument)};` : "return NA;");
        return;
      }
      default:
        throw new PineUnsupportedError(`statement \`${node.kind}\` is not supported`, node.line, node.col);
    }
  }

  /** Hoisted `var` declarations are written outside the bar loop. */
  private outerLine(text: string): void {
    this.hoisted.push("  ".repeat(this.depth) + text);
  }

  private hoisted: string[] = [];

  private expr(node: Node): string {
    switch (node.kind) {
      case "NumberLit":
        return String(node.value);
      case "StringLit":
        return JSON.stringify(node.value);
      case "BoolLit":
        return String(node.value);
      case "NaLit":
        return "NA";
      case "Identifier":
        return this.safeName(node.name, node.line, node.col);
      case "MemberExpr": {
        const DENIED_MEMBERS = new Set(["constructor", "__proto__", "prototype", "then", "call", "apply", "bind", "toString", "valueOf"]);
        if (DENIED_MEMBERS.has(node.property)) {
          throw new PineUnsupportedError(`member \`${node.property}\` is not allowed`, node.line, node.col);
        }
        return `${this.expr(node.object)}.${node.property}`;
      }
      case "IndexExpr":
        return `at(${this.expr(node.object)}, ${this.expr(node.index)}, barIndex)`;
      case "CallExpr":
        return this.call(node);
      case "UnaryExpr":
        return `(${node.operator}(${this.expr(node.argument)}))`;
      case "BinaryExpr":
        return this.binary(node);
      case "TernaryExpr":
        return `(truthy(${this.expr(node.test)}, barIndex) ? (${this.expr(node.consequent)}) : (${this.expr(node.alternate)}))`;
      case "AssignExpr":
        return `(${this.expr(node.target)} ${node.operator} ${this.expr(node.value)})`;
      case "ArrayLit":
        return `[${node.elements.map((e) => this.expr(e)).join(", ")}]`;
      default:
        throw new PineUnsupportedError(`expression \`${node.kind}\` is not supported`, node.line, node.col);
    }
  }

  /**
   * Pine's `and`/`or` are word operators in source but emit as `&&`/`||`.
   * Every other binary operator maps straight through, with `==`/`!=` becoming
   * Pine's `eq`/`ne` so `na` compares correctly.
   */
  private binary(node: { operator: string; left: Node; right: Node; line: number; col: number }): string {
    const l = this.expr(node.left);
    const r = this.expr(node.right);
    switch (node.operator) {
      case "==":
        return `eq(${l}, ${r})`;
      case "!=":
        return `!eq(${l}, ${r})`;
      case "+":
        return `add(${l}, ${r})`;
      case "-":
        return `sub(${l}, ${r})`;
      case "*":
        return `mul(${l}, ${r})`;
      case "/":
        return `div(${l}, ${r})`;
      case "%":
        return `mod(${l}, ${r})`;
      // Comparisons and boolean ops collapse a series to a scalar, so they need
      // the current bar index to read the right element.
      case "<":
        return `lt(${l}, ${r}, barIndex)`;
      case "<=":
        return `le(${l}, ${r}, barIndex)`;
      case ">":
        return `gt(${l}, ${r}, barIndex)`;
      case ">=":
        return `ge(${l}, ${r}, barIndex)`;
      case "&&":
      case "and":
        return `and(${l}, ${r}, barIndex)`;
      case "||":
      case "or":
        return `or(${l}, ${r}, barIndex)`;
      default:
        return `(${l} ${node.operator} ${r})`;
    }
  }

  private call(node: { callee: Node; args: Node[]; line: number; col: number }): string {
    const callee = node.callee;
    // Keyword arguments (`qty=10`) become one trailing object so the runtime
    // helpers can pick them off by name instead of by position.
    const positional = node.args.filter((a) => !(a.kind === "AssignExpr" && a.operator === "="));
    const kwargs = node.args.filter((a): a is AssignExpr =>
      a.kind === "AssignExpr" && a.operator === "=" && a.target.kind === "Identifier",
    );
    // Keyword arguments (`color=…`) become one options object. The generic call
    // path appends it last, but plot/order/input sinks take it in a fixed slot
    // right after their plumbing — otherwise a kwargs-only call slides the
    // object into whatever positional parameter happens to come first.
    const posArgs = positional.map((a) => this.expr(a));
    const opts = kwargs.length
      ? `{ ${kwargs.map((k) => `${(k.target as Identifier).name}: ${this.expr(k.value)}`).join(", ")} }`
      : "{}";
    const args = kwargs.length ? [...posArgs, opts] : posArgs;
    const sinkCall = (fn: string): string =>
      `${fn}(${this.nextPlotSite()}, barIndex, plots, ${opts}${posArgs.length ? `, ${posArgs.join(", ")}` : ""})`;
    const orderCall = (fn: string): string =>
      `${fn}(barIndex, orders, ${opts}${posArgs.length ? `, ${posArgs.join(", ")}` : ""})`;
    const inputEmit = (fn: string): string =>
      `${fn}(inputs, ${this.nextInputSite()}, ${opts}${posArgs.length ? `, ${posArgs.join(", ")}` : ""})`;

    if (callee.kind === "MemberExpr") {
      const obj = callee.object;
      const ns = obj.kind === "Identifier" ? obj.name : "";

      // Plotting and order functions are script-level sinks, so they bypass the
      // `ta`/`math` namespaces and call the runtime helpers directly. The bar
      // index, the sink, and the stable call-site id come first so they never
      // collide with Pine's own positional arguments.
      if (ns === "" && callee.property === "plot") return sinkCall("plotCall");
      if (ns === "" && callee.property === "plotshape") return sinkCall("shapeCall");
      if (ns === "" && callee.property === "bgcolor") return sinkCall("bgcolorCall");
      if (ns === "" && callee.property === "input") return inputEmit("inputScalar");

      // `ta.tr`/`ta.atr` take the context rather than a series, so they are
      // special-cased instead of going through the namespace table.
      if (ns === "ta" && callee.property === "tr") return `ta.tr(ctx)`;
      if (ns === "ta" && callee.property === "atr") return `ta.atr(ctx, ${args[0] ?? "14"})`;
      if (ns === "input" && ["int", "float", "bool", "string"].includes(callee.property)) {
        return inputEmit("inputCall");
      }
      if (ns === "color" && callee.property === "new") return `color.new(${args.join(", ")})`;

      // Strategy orders write into the shared `orders` sink, so they get the
      // bar index and the sink prepended like the plotting helpers do.
      if (ns === "strategy" && ["entry", "close", "exit", "close_all"].includes(callee.property)) {
        const helper =
          callee.property === "entry" ? "strategyEntry" :
          callee.property === "close" ? "strategyClose" :
          callee.property === "exit" ? "strategyExit" : "strategyCloseAll";
        return orderCall(helper);
      }

      const fn = ns ? `${ns}.${callee.property}` : callee.property;
      return `${fn}(${args.join(", ")})`;
    }

    if (callee.kind === "Identifier") {
      // Bare `input(…)` is the v4 name for `input.int`.
      if (callee.name === "input") return inputEmit("inputCall");
      if (callee.name === "nz") return `nz(${args[0] ?? "NA"}${args[1] ? `, ${args[1]}` : ""})`;
      if (callee.name === "na") return `isNa(${args[0] ?? "NA"})`;
      if (callee.name === "crossover") return `crossover(${args.join(", ")})`;
      if (callee.name === "crossunder") return `crossunder(${args.join(", ")})`;
      if (callee.name === "plot") return sinkCall("plotCall");
      if (callee.name === "plotshape") return sinkCall("shapeCall");
      if (callee.name === "bgcolor") return sinkCall("bgcolorCall");
      return `${this.safeName(callee.name, callee.line, callee.col)}(${args.join(", ")})`;
    }

    throw new PineUnsupportedError("indirect calls are not supported", node.line, node.col);
  }

  /** Prefix user bindings so they cannot shadow runtime helpers like `add`. */
  private safeName(name: string, line: number = 0, col: number = 0): string {
    if (BUILTIN_NAMES.has(name)) return `__user_${name}`;
    if (DANGEROUS_GLOBALS.has(name)) {
      throw new PineUnsupportedError(`identifier \`${name}\` is not allowed`, line, col);
    }
    return name;
  }

  toString(): string {
    // Hoisted `var` lines land before the loop so their value persists.
    const hoisted = this.hoisted.length ? `${this.hoisted.join("\n")}\n` : "";
    return hoisted + this.lines.join("\n");
  }
}

